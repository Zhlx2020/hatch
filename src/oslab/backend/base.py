"""Debug backend interface. Screens and web layers only ever see this."""
from typing import Protocol


class DebugBackend(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...

    @property
    def alive(self) -> bool: ...

    # execution
    def cont(self) -> None: ...
    def step(self) -> str: ...
    def break_at(self, addr: int) -> None: ...
    def reset(self) -> None: ...

    # observation
    def registers(self) -> str: ...
    def disassemble(self, addr: int, count: int = 8) -> str: ...
    def read_mem(self, addr: int, count: int) -> bytes: ...
    def page_walk(self, addr: int) -> str: ...
    def log_tail(self, n: int = 20) -> list: ...
